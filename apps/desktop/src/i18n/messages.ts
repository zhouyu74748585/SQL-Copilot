function wrapWithWhitespace(source: string, translated: string): string {
  const matched = source.match(/^(\s*)([\s\S]*?)(\s*)$/);
  if (!matched) {
    return translated;
  }
  return `${matched[1]}${translated}${matched[3]}`;
}

function translateCore(text: string, targetLocale: AppLocale, depth: number): string {
  if (!text || depth > 3) {
    return text;
  }

  const exact = targetLocale === 'en-US' ? zhToEnExact[text] : enToZhExact[text];
  if (exact) {
    return exact;
  }

  const translateNested = (value: string) => translateCore(value, targetLocale, depth + 1);
  for (const rule of rules) {
    const matched = targetLocale === 'en-US' ? text.match(rule.zhPattern) : text.match(rule.enPattern);
    if (!matched) {
      continue;
    }
    return targetLocale === 'en-US'
      ? rule.toEnglish(matched, translateNested)
      : rule.toChinese(matched, translateNested);
  }

  return text;
}

export function translateTextForLocale(text: string, targetLocale: AppLocale): string {
  if (!text) {
    return text;
  }
  const matched = text.match(/^(\s*)([\s\S]*?)(\s*)$/);
  if (!matched || !matched[2]) {
    return text;
  }
  const translated = translateCore(matched[2], targetLocale, 0);
  return translated === matched[2] ? text : wrapWithWhitespace(text, translated);
}
