type QueryRuntimeKey = typeof queryRuntimeKeys[number];

export function createStudioQueryRuntime<T extends StudioRuntimeState>(state: T) {
  const runtime = {} as Pick<T, Extract<QueryRuntimeKey, keyof T>>;
  queryRuntimeKeys.forEach((key) => {
    if (key in state) {
      (runtime as Record<string, unknown>)[key] = state[key];
    }
  });
  return runtime;
}
